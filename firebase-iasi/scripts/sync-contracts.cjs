const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(__dirname, '../functions/src/contracts.ts'), 'utf8');
const output = '// Generated by firebase-iasi/scripts/sync-contracts.cjs. Do not edit by hand.\n' + source;
for (const target of ['demo/lib/foundation-contracts.ts', '../expo-mobile-app/lib/foundation/contracts.ts']) {
  const file = path.resolve(root, target);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, output);
}
console.log('Foundation contracts synchronized.');

for (const name of ['booking-details.ts', 'romaniaLocations.ts']) {
  const content = fs.readFileSync(path.join(__dirname, '../functions/src', name), 'utf8');
  for (const dir of ['demo/lib', '../expo-mobile-app/lib/foundation']) {
    fs.writeFileSync(path.resolve(root, dir, name), '// Generated by sync-contracts.cjs. Do not edit by hand.\n' + content);
  }
}
